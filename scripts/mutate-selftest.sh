#!/usr/bin/env bash
# End-to-end sentinel: weak tests must survive, strong assertions must kill.
set -Eeuo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
work=$(mktemp -d "${TMPDIR:-/tmp}/mediaz-mutate-selftest.XXXXXX")
trap 'rm -rf -- "$work"' EXIT
mkdir -p "$work/scripts" "$work/pkg/sample/child" "$work/pkg/constant" "$work/pkg/uncompilable" "$work/bin"
cp "$root/scripts/mutate.sh" "$work/scripts/"
printf 'module example.invalid/mutation-feedback\n\ngo 1.26.0\n' > "$work/go.mod"
cat > "$work/pkg/sample/sample.go" <<'EOF'
package sample

func Allowed(n int) bool { return n > 0 }
EOF
cat > "$work/pkg/sample/sample_test.go" <<'EOF'
package sample

import "testing"

func TestAllowed(t *testing.T) { _ = Allowed(1) }
EOF
for ((i = 0; i < 30; i++)); do printf '// License header\n'; done > "$work/pkg/sample/generated.go"
cat >> "$work/pkg/sample/generated.go" <<'EOF'
// Code generated by mutation selftest. DO NOT EDIT.
package sample

func Generated(n int) bool { return n > 0 }
EOF
cat > "$work/pkg/sample/inactive.go" <<'EOF'
//go:build mutation_selftest_inactive

package sample

func Inactive(n int) bool { return n > 0 }
EOF
cat > "$work/pkg/sample/child/child.go" <<'EOF'
package child

func Child(n int) bool { return n > 0 }
EOF
cat > "$work/pkg/constant/constant.go" <<'EOF'
package constant

func Answer() string { return "answer" }
EOF
cd "$work"
expect() {
  local expected=$1 label=$2 status=0
  shift 2
  "$@" > "$work/output.log" 2>&1 || status=$?
  if [[ $status != "$expected" ]]; then
    printf 'FAIL %s: expected exit %s, got %s\n' "$label" "$expected" "$status" >&2
    tail -n 50 "$work/output.log" >&2
    exit 1
  fi
  printf 'PASS %s\n' "$label"
}
expect 2 'explicit package required' bash scripts/mutate.sh ''
expect 2 'recursive scope rejected' bash scripts/mutate.sh './pkg/...'
expect 2 'outside scope rejected' bash scripts/mutate.sh '../pkg/sample'
expect 2 'invalid budget rejected' env MUTATE_TIMEOUT=0 bash scripts/mutate.sh ./pkg/sample
expect 1 'weak tests expose surviving mutants' bash scripts/mutate.sh ./pkg/sample
reports=("$work"/.artifacts/mutation/pkg/sample/run.*/report.json)
weak=${reports[0]}
jq -e 'any(.files[].mutations[]; .status == "LIVED") and all(.files[]; .file_name == "sample.go")' "$weak" >/dev/null

cat > "$work/pkg/sample/sample_test.go" <<'EOF'
package sample

import "testing"

func TestAllowed(t *testing.T) {
  for _, tc := range []struct { n int; want bool }{{-1, false}, {0, false}, {1, true}} {
    if got := Allowed(tc.n); got != tc.want {
      t.Errorf("Allowed(%d) = %v; want %v", tc.n, got, tc.want)
    }
  }
}
EOF
# Personal env/config must not switch the command to dry run or set test-cpu.
printf 'unleash:\n  dry-run: true\n  test-cpu: 1\n' > "$work/.gremlins.yaml"
expect 0 'strong assertions kill mutants; generated/inactive/child files excluded' \
  env GREMLINS_UNLEASH_DRY_RUN=true GREMLINS_UNLEASH_TEST_CPU=1 GOFLAGS=-trimpath bash scripts/mutate.sh ./pkg/sample
expect 0 'warm-cache repetition stays clean' bash scripts/mutate.sh ./pkg/sample
expect 2 'no candidates is inconclusive, not clean' bash scripts/mutate.sh ./pkg/constant

# Upstream v0.6.0 falsely calls a string + -> - build failure KILLED.
# The pinned Nix patch must report it as NOT VIABLE instead of false-green.
cat > "$work/pkg/uncompilable/uncompilable.go" <<'EOF'
package uncompilable

func Join(s string) string { return s + "x" }
EOF
cat > "$work/pkg/uncompilable/uncompilable_test.go" <<'EOF'
package uncompilable

import "testing"

func TestJoin(t *testing.T) { _ = Join("a") }
EOF
expect 2 'uncompilable mutant is not an assertion kill' bash scripts/mutate.sh ./pkg/uncompilable
invalid_reports=("$work"/.artifacts/mutation/pkg/uncompilable/run.*/report.json)
jq -e 'all(.files[].mutations[]; .status == "NOT VIABLE")' "${invalid_reports[0]}" >/dev/null

# Deterministic protocol/error tests without waiting for a real mutant timeout.
# Use a valid real report as the template, replacing only statuses as needed.
cp "$weak" "$work/template.json"
cat > "$work/bin/gremlins" <<'EOF'
#!/usr/bin/env bash
set -eu
while [[ $# -gt 0 ]]; do
  if [[ $1 == --output ]]; then out=$2; shift 2; else shift; fi
done
case "$SELFTEST_MODE" in
  missing) exit 0 ;;
  malformed) printf '{broken\n' > "$out" ;;
  failure) exit 42 ;;
  timeout) sleep 10 ;;
  *) jq --arg status "$SELFTEST_MODE" '(.files[].mutations[].status) = $status' "$SELFTEST_TEMPLATE" > "$out" ;;
esac
EOF
chmod +x "$work/bin/gremlins"
export PATH="$work/bin:$PATH" SELFTEST_TEMPLATE="$work/template.json"
for mode in 'TIMED OUT' 'NOT VIABLE' SKIPPED RUNNABLE missing malformed failure; do
  expect 2 "incomplete report: $mode" env SELFTEST_MODE="$mode" bash scripts/mutate.sh ./pkg/sample
done
expect 2 'overall time budget enforced' env SELFTEST_MODE=timeout MUTATE_TIMEOUT=2 bash scripts/mutate.sh ./pkg/sample
[[ $(< "$work/output.log") == *'Gremlins failed or exceeded the time budget'* ]]
printf 'FAIL baseline\n' > "$work/pkg/sample/sample_test.go"
expect 2 'broken baseline stops before mutations' env SELFTEST_MODE=KILLED bash scripts/mutate.sh ./pkg/sample
printf '\nMutation runner selftest passed.\n'
